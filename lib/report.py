"""Stage 6 — render report drafts from the stage-5 analysis.

Deliberately deterministic: it formats the already-reviewed analysis fields into
Markdown rather than asking a model to write fresh prose into a report draft, so
the draft contains nothing that wasn't in the validated stage-5 output. Each
draft for a CONFIRMED candidate is written under reports/<program>/ with:
  * a [HUMAN REVIEW REQUIRED] banner at the very top (kept until you clear it),
  * an AI-assisted disclosure note when the program requires it,
  * a NOT-SUBMITTED footer (gate G3 — submission is manual, by the operator).

Nothing is submitted anywhere. This module only writes files.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from lib.scope_guard import load_scope  # noqa: E402

BANNER = "> **[HUMAN REVIEW REQUIRED]** — this draft is UNVERIFIED and UNSUBMITTED. Confirm every claim yourself, then remove this banner."
DISCLOSURE = "> **Tooling:** AI-assisted (Claude + optional local model) with human review."
FOOTER = ("---\n_Generated by bb-agent (stage 6). NOT submitted — submission is manual, "
          "by the operator (gate G3). No destructive or out-of-policy testing was performed._")


def _slug(text: str) -> str:
    return re.sub(r"[^a-z0-9._-]+", "-", text.lower()).strip("-") or "finding"


def render_report(candidate: dict, program: str, ai_disclosure: bool) -> str:
    a = candidate.get("analysis", {})
    hosts = ", ".join(candidate.get("hosts", [])) or "—"
    templates = ", ".join(candidate.get("templates", [])) or "—"
    cvss = a.get("cvss_vector") or "n/a"
    steps = a.get("reproduction_outline", []) or ["(none provided)"]
    repro = "\n".join(f"{i}. {s}" for i, s in enumerate(steps, 1))
    oop = a.get("out_of_policy_to_prove", False)
    oop_line = ("**Yes** — proving this would require actions outside program policy. "
                "Do NOT attempt them; hand this to a human to assess."
                if oop else "No — minimal, in-policy proof is sufficient.")

    head = [f"# [HUMAN REVIEW REQUIRED] {candidate.get('title', candidate.get('id'))}", "", BANNER]
    if ai_disclosure:
        head.append(DISCLOSURE)
    head.append("")

    body = [
        f"- **Program:** {program}",
        f"- **Assets:** {hosts}",
        f"- **Severity (proposed):** {a.get('severity', 'info')}  ·  **CVSS:** {cvss}",
        f"- **Detected by:** {templates}",
        f"- **In scope:** {a.get('in_scope', False)}  ·  **Confirmed:** {a.get('confirmed', False)}",
        "",
        "## Summary",
        a.get("exploitability", "(no summary)"),
        "",
        "## Reproduction (outline — high-level, non-destructive)",
        repro,
        "",
        "## Impact / notes",
        a.get("notes", "(none)"),
        "",
        "## Out-of-policy to prove?",
        oop_line,
        "",
        "## Remediation",
        "Address the underlying issue flagged by the detection template(s) above; "
        "confirm the fix against the same check.",
        "",
        FOOTER,
    ]
    return "\n".join(head + body) + "\n"


def write_reports(analyzed: dict, program: str, ai_disclosure: bool, out_dir: Path) -> list[Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for c in analyzed.get("candidates", []):
        if not c.get("analysis", {}).get("confirmed"):
            continue
        path = out_dir / f"{_slug(c['id'])}.md"
        path.write_text(render_report(c, program, ai_disclosure))
        written.append(path)
    return written


if __name__ == "__main__":
    args = sys.argv[1:]
    if len(args) != 2:
        print("usage: report.py <program> <analyzed.json>", file=sys.stderr)
        raise SystemExit(2)
    program, infile = args
    analyzed = json.load(open(infile))
    try:
        ai_disclosure = load_scope(program).get("ai_disclosure_required", True)
    except Exception:
        ai_disclosure = True  # fail safe: disclose
    out_dir = ROOT / "reports" / program
    written = write_reports(analyzed, program, ai_disclosure, out_dir)
    for p in written:
        print(p)
    if not written:
        print(f"# no confirmed candidates to draft (of "
              f"{len(analyzed.get('candidates', []))}). Nothing written.", file=sys.stderr)
    raise SystemExit(0)
